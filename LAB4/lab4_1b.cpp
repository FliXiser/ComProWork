#include <iostream>
#include <cmath>
using namespace std;
int main(){
    cout << "abs of -2 = " << abs(-2) << endl;
    // pow = (ตัวเลขที่จะเอามาคูณตัวเอง , จำนวนครั้งที่ต้องการให้คูณตัวเอง)
    cout << "power 3 of 2 (2^3) = " << pow(2 , 3) << endl;
    cout << "root two of 4 = " << sqrt(4) << endl;
    return 0;
}